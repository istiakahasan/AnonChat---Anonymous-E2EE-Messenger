import 'dart:convert';
import 'dart:typed_data';
import 'package:cryptography/cryptography.dart';

/// Double Ratchet State representation for AnonChat Flutter client
class DoubleRatchetSession {
  SimpleKeyPair? dhsKeypair;
  PublicKey? dhrPublic;
  SecretKey rootKey;
  SecretKey? sendingChainKey;
  SecretKey? receivingChainKey;
  int ns;
  int nr;
  int pns;
  Map<String, SecretKey> mkSkipped;
  bool bobFirstMessage;

  DoubleRatchetSession({
    this.dhsKeypair,
    this.dhrPublic,
    required this.rootKey,
    this.sendingChainKey,
    this.receivingChainKey,
    this.ns = 0,
    this.nr = 0,
    this.pns = 0,
    Map<String, SecretKey>? mkSkipped,
    this.bobFirstMessage = false,
  }) : mkSkipped = mkSkipped ?? {};

  /// Sender State (Alice, who initiated X3DH)
  ///
  /// Inputs:
  /// - `sharedSecret`: 32-byte output from X3DH
  /// - `bobRatchetPublic`: Bob's signed prekey public key
  ///
  /// Initialize:
  /// - `DHs` = a NEW X25519 keypair generated by Alice for this session
  /// - `DHr` = `bobRatchetPublic`
  /// - `RK` = HKDF(shared_secret, DH(DHs_private, DHr), info="root")
  /// - `CKs` = HKDF(RK, info="chain-send")
  /// - `CKr` = null
  /// - `Ns` = 0, `Nr` = 0, `PNs` = 0
  /// - `MKSKIPPED` = empty map
  /// - `BOB_FIRST_MESSAGE` = false
  static Future<DoubleRatchetSession> initSenderState({
    required List<int> sharedSecret,
    required List<int> bobRatchetPublic,
  }) async {
    final x25519 = X25519();
    final dhsKeypair = await x25519.newKeyPair();
    final bobPub = SimplePublicKey(bobRatchetPublic, type: KeyPairType.x25519);

    final dhSharedSecret = await x25519.sharedSecretKey(
      keyPair: dhsKeypair,
      remotePublicKey: bobPub,
    );
    final dhBytes = await dhSharedSecret.extractBytes();

    final hkdf = Hkdf(hmac: Hmac.sha256(), outputLength: 64);
    final derived = await hkdf.deriveKey(
      secretKey: SecretKey(sharedSecret),
      nonce: dhBytes,
      info: utf8.encode('AnonChat_DoubleRatchet_RootKDF'),
    );
    final okm = await derived.extractBytes();
    final newRk = okm.sublist(0, 32);
    final cks = okm.sublist(32, 64);

    return DoubleRatchetSession(
      dhsKeypair: dhsKeypair,
      dhrPublic: bobPub,
      rootKey: SecretKey(newRk),
      sendingChainKey: SecretKey(cks),
      receivingChainKey: null,
      ns: 0,
      nr: 0,
      pns: 0,
      mkSkipped: {},
      bobFirstMessage: false,
    );
  }

  /// Receiver State (Bob)
  ///
  /// Inputs:
  /// - `sharedSecret`: same 32 bytes from X3DH
  /// - `bobRatchetKeypair`: Bob's signed prekey keypair (private + public)
  ///
  /// Initialize:
  /// - `DHs` = `bobRatchetKeypair`
  /// - `DHr` = null
  /// - `RK` = `sharedSecret`
  /// - `CKs` = null, `CKr` = null
  /// - `Ns` = 0, `Nr` = 0, `PNs` = 0
  /// - `MKSKIPPED` = empty map
  /// - `BOB_FIRST_MESSAGE` = true
  static DoubleRatchetSession initReceiverState({
    required List<int> sharedSecret,
    required SimpleKeyPair bobRatchetKeypair,
  }) {
    return DoubleRatchetSession(
      dhsKeypair: bobRatchetKeypair,
      dhrPublic: null,
      rootKey: SecretKey(sharedSecret),
      sendingChainKey: null,
      receivingChainKey: null,
      ns: 0,
      nr: 0,
      pns: 0,
      mkSkipped: {},
      bobFirstMessage: true,
    );
  }
}
