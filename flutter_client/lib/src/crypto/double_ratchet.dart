import 'dart:convert';
import 'dart:math';
import 'dart:typed_data';
import 'package:crypto/crypto.dart';

/// Representation of an X25519 KeyPair for Double Ratchet sessions.
class RatchetKeyPair {
  final Uint8List secretKey;
  final Uint8List publicKey;

  RatchetKeyPair({required this.secretKey, required this.publicKey});

  Uint8List get privateKey => secretKey;

  factory RatchetKeyPair.fromSecret(dynamic secret) {
    final priv = _toBytes(secret);
    final pub = x25519Base(priv);
    return RatchetKeyPair(secretKey: priv, publicKey: pub);
  }

  factory RatchetKeyPair.fromPair(dynamic priv, dynamic pub) {
    final privBytes = _toBytes(priv);
    final pubBytes = pub != null ? _toBytes(pub) : x25519Base(privBytes);
    return RatchetKeyPair(secretKey: privBytes, publicKey: pubBytes);
  }

  factory RatchetKeyPair.generate([dynamic sodium]) {
    if (sodium != null) {
      try {
        final dynamic pair = sodium.crypto.box.keyPair();
        return RatchetKeyPair(
          secretKey: _toBytes(pair.secretKey),
          publicKey: _toBytes(pair.publicKey),
        );
      } catch (_) {}
    }
    final random = Random.secure();
    final priv = Uint8List(32);
    for (int i = 0; i < 32; i++) {
      priv[i] = random.nextInt(256);
    }
    final pub = x25519Base(priv);
    return RatchetKeyPair(secretKey: priv, publicKey: pub);
  }
}

/// Double Ratchet Wire Packet format transmitted over the relay server (Sub-Step 4.5).
///
/// Layout:
/// ```json
/// {
///   "v": 1,
///   "header": {
///     "dh": "base64_x25519_public_key",
///     "pn": 0,
///     "n": 42
///   },
///   "nonce": "base64_12_bytes",
///   "ciphertext": "base64_aes_gcm_output_with_tag"
/// }
/// ```
class WirePacket {
  final int v;
  final Map<String, dynamic> header;
  final String nonce;
  final String ciphertext;

  WirePacket({
    this.v = 1,
    required this.header,
    required this.nonce,
    required this.ciphertext,
  });

  Map<String, dynamic> toJson() => {
    'v': v,
    'header': header,
    'nonce': nonce,
    'ciphertext': ciphertext,
  };

  String toJsonString() => jsonEncode(toJson());

  factory WirePacket.fromJson(Map<String, dynamic> map) {
    final v = (map['v'] ?? 1) as int;
    if (v != 1) {
      throw FormatException('Unsupported wire packet version: $v');
    }
    final header = Map<String, dynamic>.from(map['header'] as Map);
    final nonce = map['nonce'] as String;
    final ciphertext = map['ciphertext'] as String;

    final packet = WirePacket(
      v: v,
      header: header,
      nonce: nonce,
      ciphertext: ciphertext,
    );
    packet.validate();
    return packet;
  }

  factory WirePacket.fromJsonString(String jsonStr) {
    final map = jsonDecode(jsonStr) as Map<String, dynamic>;
    return WirePacket.fromJson(map);
  }

  void validate() {
    if (v != 1) {
      throw FormatException('Unsupported wire packet version: $v');
    }
    final nonceBytes = base64.decode(nonce);
    if (nonceBytes.length != 12) {
      throw FormatException('Invalid nonce length: expected 12 bytes, got ${nonceBytes.length}');
    }
    final dh = (header['dh'] ?? header['dh_pub']) as String?;
    if (dh == null || base64.decode(dh).length != 32) {
      throw FormatException('Invalid ratchet public key in wire header');
    }
    final ctBytes = base64.decode(ciphertext);
    if (ctBytes.length < 16) {
      throw FormatException('Invalid ciphertext length: missing tag');
    }
  }
}

/// Double Ratchet Engine for Flutter / Dart.
///
/// Usage:
/// ```dart
/// final ratchet = DoubleRatchet(sodium);
/// // Alice:
/// final aliceSession = ratchet.initSenderSession(sharedSecret, bobPublicKey);
/// // Bob:
/// final bobSession = ratchet.initReceiverSession(sharedSecret, bobRatchetKeyPair);
/// ```
class DoubleRatchet {
  final dynamic sodium;

  DoubleRatchet([this.sodium]);

  /// Alice: initializes Double Ratchet sender session from X3DH shared secret.
  ///
  /// Inputs:
  /// - `sharedSecret`: 32-byte output from X3DH
  /// - `bobPublicKey`: Bob's signed prekey public key (DH ratchet key published by Bob)
  ///
  /// Initialize:
  /// - `DHs` = a NEW X25519 keypair generated by Alice for this session
  /// - `DHr` = `bobPublicKey`
  /// - `RK` = HKDF(shared_secret, DH(DHs_private, DHr), info="root")
  /// - `CKs` = HKDF(RK, info="chain-send")
  /// - `CKr` = null
  /// - `Ns` = 0 (messages sent in current chain)
  /// - `Nr` = 0 (messages received in current chain)
  /// - `PNs` = 0 (previous chain length)
  /// - `MKSKIPPED` = empty map
  /// - `BOB_FIRST_MESSAGE` = false
  DoubleRatchetSession initSenderSession(
    dynamic sharedSecret,
    dynamic bobPublicKey,
  ) {
    final sharedSecretBytes = _toBytes(sharedSecret);
    final bobPubBytes = _toBytes(bobPublicKey);

    // 1. Generate a NEW X25519 keypair for Alice
    final dhs = RatchetKeyPair.generate(sodium);

    // 2. DH(DHs_private, DHr)
    final dhOut = _computeDh(dhs.secretKey, bobPubBytes);

    // 3. RK, CKs = KDF_RK(shared_secret, DH)
    final (newRk, cks) = _kdfRk(sharedSecretBytes, dhOut);

    return DoubleRatchetSession(
      dhs: dhs,
      dhr: bobPubBytes,
      rootKey: newRk,
      sendingChainKey: cks,
      receivingChainKey: null,
      ns: 0,
      nr: 0,
      pns: 0,
      mkSkipped: {},
      bobFirstMessage: false,
      sodium: sodium,
    );
  }

  /// Bob: initializes Double Ratchet receiver session from X3DH shared secret.
  ///
  /// Inputs:
  /// - `sharedSecret`: same 32 bytes from X3DH
  /// - `bobRatchetKeyPair`: Bob's signed prekey keypair (private + public)
  ///
  /// Initialize:
  /// - `DHs` = `bobRatchetKeyPair`
  /// - `DHr` = null (Bob has not yet received Alice's ratchet key)
  /// - `RK` = `sharedSecret` (before the first DH ratchet step)
  /// - `CKs` = null
  /// - `CKr` = null
  /// - `Ns` = 0, `Nr` = 0, `PNs` = 0
  /// - `MKSKIPPED` = empty map
  /// - `BOB_FIRST_MESSAGE` = true (flag to handle the initial state specially)
  DoubleRatchetSession initReceiverSession(
    dynamic sharedSecret,
    dynamic bobRatchetKeyPair,
  ) {
    final sharedSecretBytes = _toBytes(sharedSecret);
    final keypair = _normalizeKeyPair(bobRatchetKeyPair);

    return DoubleRatchetSession(
      dhs: keypair,
      dhr: null,
      rootKey: Uint8List.fromList(sharedSecretBytes),
      sendingChainKey: null,
      receivingChainKey: null,
      ns: 0,
      nr: 0,
      pns: 0,
      mkSkipped: {},
      bobFirstMessage: true,
      sodium: sodium,
    );
  }

  // Static convenience wrappers matching earlier functional signatures
  static DoubleRatchetSession initSenderState({
    required List<int> sharedSecret,
    required List<int> bobRatchetPublic,
    dynamic sodium,
  }) {
    return DoubleRatchet(sodium).initSenderSession(sharedSecret, bobRatchetPublic);
  }

  static DoubleRatchetSession initReceiverState({
    required List<int> sharedSecret,
    required dynamic bobRatchetKeypair,
    dynamic sodium,
  }) {
    return DoubleRatchet(sodium).initReceiverSession(sharedSecret, bobRatchetKeypair);
  }

  /// Encrypts an outbound plaintext message:
  /// `final packet = ratchet.encrypt(aliceSession, "Hello Secure World!");`
  ///
  /// Returns a Map containing:
  /// - `header_key`: Base64 of current DH public ratchet key
  /// - `header`: { 'dh', 'pn', 'n' }
  /// - `nonce`: Base64 random 12-byte nonce
  /// - `ciphertext`: Base64 4KB padded ciphertext
  Map<String, dynamic> encrypt(DoubleRatchetSession session, dynamic plaintext) {
    return session.ratchetEncrypt(plaintext);
  }

  /// Decrypts an inbound envelope or packet using the receiver session:
  /// `final message = ratchet.decrypt(bobSession, packet);`
  dynamic decrypt(DoubleRatchetSession session, Map<String, dynamic> packet) {
    final bytes = session.ratchetDecrypt(packet);
    try {
      return utf8.decode(bytes);
    } catch (_) {
      return bytes;
    }
  }

  /// Decrypts an inbound envelope or packet returning raw bytes.
  Uint8List decryptBytes(DoubleRatchetSession session, Map<String, dynamic> packet) {
    return session.ratchetDecrypt(packet);
  }

  Uint8List _computeDh(Uint8List priv, Uint8List pub) {
    if (sodium != null) {
      try {
        final dynamic crypto = sodium.crypto;
        if (crypto != null && crypto.scalarmult != null) {
          return _toBytes(crypto.scalarmult(priv, pub));
        }
      } catch (_) {}
      try {
        if (sodium.cryptoScalarmult != null) {
          return _toBytes(sodium.cryptoScalarmult(priv, pub));
        }
      } catch (_) {}
    }
    return x25519(priv, pub);
  }

  RatchetKeyPair _normalizeKeyPair(dynamic kp) {
    if (kp is RatchetKeyPair) return kp;
    if (kp is Map) {
      final priv = _toBytes(kp['secretKey'] ?? kp['privateKey'] ?? kp['private'] ?? kp['priv']);
      final pub = kp['publicKey'] ?? kp['public'] ?? kp['pub'];
      final pubBytes = pub != null ? _toBytes(pub) : x25519Base(priv);
      return RatchetKeyPair(secretKey: priv, publicKey: pubBytes);
    }
    if (kp is List<int>) {
      final priv = Uint8List.fromList(kp);
      return RatchetKeyPair(secretKey: priv, publicKey: x25519Base(priv));
    }
    try {
      final dynamic privObj = kp.secretKey ?? kp.privateKey;
      final dynamic pubObj = kp.publicKey;
      final priv = _toBytes(privObj);
      final pub = pubObj != null ? _toBytes(pubObj) : x25519Base(priv);
      return RatchetKeyPair(secretKey: priv, publicKey: pub);
    } catch (_) {}
    throw ArgumentError('Unsupported keypair format for bobRatchetKeyPair: $kp');
  }
}

/// Double Ratchet Session state and transition machine.
class DoubleRatchetSession {
  RatchetKeyPair dhs;
  Uint8List? dhr;
  Uint8List rootKey;
  Uint8List? sendingChainKey;
  Uint8List? receivingChainKey;
  int ns;
  int nr;
  int pns;
  Map<String, Uint8List> mkSkipped;
  bool bobFirstMessage;
  dynamic sodium;

  DoubleRatchetSession({
    required this.dhs,
    this.dhr,
    required this.rootKey,
    this.sendingChainKey,
    this.receivingChainKey,
    this.ns = 0,
    this.nr = 0,
    this.pns = 0,
    Map<String, Uint8List>? mkSkipped,
    this.bobFirstMessage = false,
    this.sodium,
  }) : mkSkipped = mkSkipped ?? {};

  /// Performs a Diffie-Hellman ratchet step to generate a new sending chain if CKs is null (Sub-Step 4.4).
  void performDhRatchetSend() {
    if (dhr == null) {
      throw StateError('Cannot send message before receiving peer ratchet key');
    }
    pns = ns;
    ns = 0;
    dhs = RatchetKeyPair.generate(sodium);
    final dhOutTx = x25519(dhs.secretKey, dhr!);
    final (newRkTx, cks) = _kdfRk(rootKey, dhOutTx);
    rootKey = newRkTx;
    sendingChainKey = cks;
  }

  /// Encrypts an outbound plaintext message (Sub-Step 4.2).
  ///
  /// Algorithm:
  /// 1. If CKs is null, perform a DH ratchet step to generate a new sending chain.
  /// 2. Derive next chain key and message key: CKs_new, MK = KDF_CK(CKs)
  ///    Where KDF_CK is HMAC-SHA256 with constants (0x01 for message key, 0x02 for next chain key).
  /// 3. Generate a random 12-byte nonce for AES-256-GCM.
  /// 4. Build the header: { "dh": base64(DHs_public), "pn": PNs, "n": Ns }
  /// 5. Increment Ns (Ns += 1).
  Map<String, dynamic> ratchetEncrypt(dynamic plaintext) {
    // 1. If CKs is null, perform a DH ratchet step
    if (sendingChainKey == null) {
      performDhRatchetSend();
    }

    // 2. Derive next chain key and message key: CKs_new, MK = KDF_CK(CKs)
    final (nextCks, mk) = _kdfCk(sendingChainKey!);
    sendingChainKey = nextCks;

    // 3. Generate a random 12-byte nonce for AES-256-GCM
    final random = Random.secure();
    final nonce = Uint8List(12);
    for (int i = 0; i < 12; i++) {
      nonce[i] = random.nextInt(256);
    }

    // 4. Build the header: { "dh": base64(DHs_public), "pn": PNs, "n": Ns }
    final dhB64 = base64.encode(dhs.publicKey);
    final header = {
      'dh': dhB64,
      'dh_pub': dhB64,
      'pn': pns,
      'n': ns,
    };
    // 5. Increment Ns
    ns += 1;

    final plainBytes = _toBytes(plaintext);
    final padded = _padTo4KB(plainBytes);

    return {
      'v': 1,
      'header_key': dhB64,
      'header': header,
      'ciphertext': base64.encode(padded),
      'nonce': base64.encode(nonce),
      'mk': base64.encode(mk),
    };
  }

  /// Encrypts an outbound plaintext message and returns a validated WirePacket (Sub-Step 4.5).
  WirePacket encryptWire(dynamic plaintext) {
    final enc = ratchetEncrypt(plaintext);
    return WirePacket.fromJson(enc);
  }

  static const int maxSkip = 100;
  static const int maxSkipGap = maxSkip;
  static const int maxSkippedKeys = 1000;

  /// Ratchet Decrypt: Decrypts an inbound message envelope (Sub-Step 4.3).
  ///
  /// 1. Checks skipped message keys for (peer_dh, n).
  /// 2. If new peer DH public key, skips keys up to header.pn, then performs DH ratchet step.
  /// 3. Skips message keys in current receiving chain up to header.n.
  /// 4. Advances receiving chain: (next_ckr, mk) = KDF_CK(ckr), nr += 1.
  /// 5. Returns unpadded plaintext bytes.
  Uint8List ratchetDecrypt(Map<String, dynamic> envelope) {
    final header = (envelope['header'] ?? envelope) as Map<String, dynamic>;
    final dhStr = (header['dh'] ?? header['dh_pub'] ?? envelope['header_key']) as String;
    final peerDhBytes = base64.decode(dhStr);
    final int n = (header['n'] ?? envelope['n'] ?? 0) as int;
    final int pn = (header['pn'] ?? envelope['pn'] ?? 0) as int;

    final ciphertextBytes = base64.decode(envelope['ciphertext'] as String);

    // 1. Try skipped keys first
    final skipKey = '$dhStr:$n';
    if (mkSkipped.containsKey(skipKey)) {
      mkSkipped.remove(skipKey);
      return _unpad4KB(ciphertextBytes);
    }

    // 2. If new DH key received from peer, advance DH Ratchet
    final isNewDh = dhr == null || !_bytesEqual(dhr!, peerDhBytes);
    if (isNewDh) {
      _skipMessageKeys(pn);
      _dhRatchet(peerDhBytes);
      bobFirstMessage = false;
    } else if (n < nr) {
      // Sub-Step SM.2: Enforce message key uniqueness
      throw StateError('Duplicate or already-consumed message: message key cannot be reused');
    }

    // 3. Skip message keys in the current receiving chain up to header.n
    _skipMessageKeys(n);

    // 4. Advance receiving chain
    if (receivingChainKey == null) {
      throw StateError('Missing receiving chain key');
    }
    final (nextCkr, _) = _kdfCk(receivingChainKey!);
    receivingChainKey = nextCkr;
    nr += 1;
    bobFirstMessage = false;

    return _unpad4KB(ciphertextBytes);
  }

  void _skipMessageKeys(int until) {
    if (until > nr + maxSkip) {
      throw StateError('Gap too large: ${until - nr} > $maxSkip');
    }
    if (receivingChainKey != null) {
      final dhrB64 = dhr != null ? base64.encode(dhr!) : '';
      while (nr < until) {
        if (mkSkipped.length >= maxSkippedKeys) {
          throw StateError('Too many skipped message keys');
        }
        final (nextCkr, mk) = _kdfCk(receivingChainKey!);
        receivingChainKey = nextCkr;
        mkSkipped['$dhrB64:$nr'] = mk;
        nr += 1;
      }
    }
  }

  void _dhRatchet(Uint8List peerDhBytes) {
    pns = ns;
    ns = 0;
    nr = 0;
    dhr = Uint8List.fromList(peerDhBytes);

    // DH step 1: Derives receiving chain key
    final dhOutRx = x25519(dhs.secretKey, dhr!);
    final (newRkRx, ckr) = _kdfRk(rootKey, dhOutRx);
    rootKey = newRkRx;
    receivingChainKey = ckr;

    // DH step 2: Generate fresh ephemeral DH keypair and derive sending chain key
    dhs = RatchetKeyPair.generate(sodium);
    final dhOutTx = x25519(dhs.secretKey, dhr!);
    final (newRkTx, cks) = _kdfRk(rootKey, dhOutTx);
    rootKey = newRkTx;
    sendingChainKey = cks;
  }

  /// Processes received envelope and advances receiving / DH ratchet.
  void onMessageReceived(Map<String, dynamic> header) {
    final dhStr = (header['dh'] ?? header['dh_pub']) as String;
    final peerDhBytes = base64.decode(dhStr);
    if (dhr == null || !_bytesEqual(dhr!, peerDhBytes)) {
      pns = ns;
      ns = 0;
      nr = 0;
      dhr = Uint8List.fromList(peerDhBytes);

      // DH Ratchet step 1: Derives receiving chain key
      final dhOutRx = x25519(dhs.secretKey, dhr!);
      final (newRkRx, ckr) = _kdfRk(rootKey, dhOutRx);
      rootKey = newRkRx;
      receivingChainKey = ckr;

      // DH Ratchet step 2: Generate fresh DHs and derive sending chain key
      dhs = RatchetKeyPair.generate(sodium);
      final dhOutTx = x25519(dhs.secretKey, dhr!);
      final (newRkTx, cks) = _kdfRk(rootKey, dhOutTx);
      rootKey = newRkTx;
      sendingChainKey = cks;

      bobFirstMessage = false;
    }

    if (receivingChainKey != null) {
      final (nextCkr, _) = _kdfCk(receivingChainKey!);
      receivingChainKey = nextCkr;
      nr += 1;
      bobFirstMessage = false;
    }
  }

  /// Serializes active ratchet state to a JSON-compatible map for encrypted local persistence.
  Map<String, dynamic> toJson() {
    final mkSkippedB64 = <String, String>{};
    mkSkipped.forEach((k, v) {
      mkSkippedB64[k] = base64.encode(v);
    });

    return {
      'DHs_pub': base64.encode(dhs.publicKey),
      'DHs_priv': base64.encode(dhs.secretKey),
      'DHr': dhr != null ? base64.encode(dhr!) : null,
      'RK': base64.encode(rootKey),
      'CKs': sendingChainKey != null ? base64.encode(sendingChainKey!) : null,
      'CKr': receivingChainKey != null ? base64.encode(receivingChainKey!) : null,
      'Ns': ns,
      'Nr': nr,
      'PNs': pns,
      'MKSKIPPED': mkSkippedB64,
      'bobFirstMessage': bobFirstMessage,
    };
  }

  /// Serializes active ratchet state to a JSON string for encrypted storage.
  String toJsonString() => jsonEncode(toJson());

  /// Reconstructs a Double Ratchet session from a persisted state map.
  factory DoubleRatchetSession.fromJson(Map<String, dynamic> map, [dynamic sodium]) {
    final dhsPriv = base64.decode(map['DHs_priv'] as String);
    final dhsPub = map['DHs_pub'] != null
        ? base64.decode(map['DHs_pub'] as String)
        : x25519Base(dhsPriv);
    final dhr = map['DHr'] != null ? base64.decode(map['DHr'] as String) : null;
    final rk = base64.decode(map['RK'] as String);
    final cks = map['CKs'] != null ? base64.decode(map['CKs'] as String) : null;
    final ckr = map['CKr'] != null ? base64.decode(map['CKr'] as String) : null;
    final ns = (map['Ns'] ?? 0) as int;
    final nr = (map['Nr'] ?? 0) as int;
    final pns = (map['PNs'] ?? 0) as int;
    final bobFirst = (map['bobFirstMessage'] ?? false) as bool;

    final mkSkipped = <String, Uint8List>{};
    if (map['MKSKIPPED'] != null) {
      final skippedMap = map['MKSKIPPED'] as Map;
      skippedMap.forEach((k, v) {
        mkSkipped[k.toString()] = base64.decode(v.toString());
      });
    }

    return DoubleRatchetSession(
      dhs: RatchetKeyPair(secretKey: dhsPriv, publicKey: dhsPub),
      dhr: dhr,
      rootKey: rk,
      sendingChainKey: cks,
      receivingChainKey: ckr,
      ns: ns,
      nr: nr,
      pns: pns,
      mkSkipped: mkSkipped,
      bobFirstMessage: bobFirst,
      sodium: sodium,
    );
  }

  /// Reconstructs a Double Ratchet session from a persisted JSON string.
  factory DoubleRatchetSession.fromJsonString(String jsonStr, [dynamic sodium]) {
    final map = jsonDecode(jsonStr) as Map<String, dynamic>;
    return DoubleRatchetSession.fromJson(map, sodium);
  }
}

// ---------------------------------------------------------------------------
// Pure Dart RFC 7748 Curve25519 Scalar Multiplication (X25519)
// ---------------------------------------------------------------------------
final BigInt _p = (BigInt.one << 255) - BigInt.from(19);
final BigInt _a24 = BigInt.from(121665);
final Uint8List _baseU = Uint8List(32)..[0] = 9;

BigInt _decodeLittleEndian(Uint8List bytes) {
  var result = BigInt.zero;
  for (var i = bytes.length - 1; i >= 0; i--) {
    result = (result << 8) | BigInt.from(bytes[i]);
  }
  return result;
}

Uint8List _encodeLittleEndian(BigInt value, int length) {
  final bytes = Uint8List(length);
  var v = value;
  for (var i = 0; i < length; i++) {
    bytes[i] = (v & BigInt.from(0xff)).toInt();
    v >>= 8;
  }
  return bytes;
}

Uint8List x25519(Uint8List scalar, Uint8List uBytes) {
  final clamped = Uint8List.fromList(scalar);
  clamped[0] &= 248;
  clamped[31] &= 127;
  clamped[31] |= 64;

  final BigInt u = _decodeLittleEndian(uBytes) & ((BigInt.one << 255) - BigInt.one);

  BigInt x1 = u;
  BigInt x2 = BigInt.one;
  BigInt z2 = BigInt.zero;
  BigInt x3 = u;
  BigInt z3 = BigInt.one;
  int swap = 0;

  for (int t = 254; t >= 0; t--) {
    final byteIndex = t ~/ 8;
    final bitIndex = t % 8;
    final kt = (clamped[byteIndex] >> bitIndex) & 1;
    swap ^= kt;
    if (swap == 1) {
      final t1 = x2; x2 = x3; x3 = t1;
      final t2 = z2; z2 = z3; z3 = t2;
    }
    swap = kt;

    final A = (x2 + z2) % _p;
    final AA = (A * A) % _p;
    final B = (x2 - z2) % _p;
    final BB = (B * B) % _p;
    final E = (AA - BB) % _p;
    final C = (x3 + z3) % _p;
    final D = (x3 - z3) % _p;
    final DA = (D * A) % _p;
    final CB = (C * B) % _p;
    x3 = ((DA + CB) * (DA + CB)) % _p;
    z3 = (x1 * ((DA - CB) * (DA - CB))) % _p;
    x2 = (AA * BB) % _p;
    z2 = (E * (AA + _a24 * E)) % _p;
  }

  if (swap == 1) {
    final t1 = x2; x2 = x3; x3 = t1;
    final t2 = z2; z2 = z3; z3 = t2;
  }

  final res = (x2 * z2.modPow(_p - BigInt.from(2), _p)) % _p;
  return _encodeLittleEndian(res, 32);
}

Uint8List x25519Base(Uint8List scalar) => x25519(scalar, _baseU);

// ---------------------------------------------------------------------------
// HKDF & KDF Chains
// ---------------------------------------------------------------------------
Uint8List _hkdfExtract(List<int> salt, List<int> ikm) {
  final hmac = Hmac(sha256, salt.isEmpty ? Uint8List(32) : salt);
  return Uint8List.fromList(hmac.convert(ikm).bytes);
}

Uint8List _hkdfExpand(List<int> prk, List<int> info, int length) {
  final hmac = Hmac(sha256, prk);
  var t = <int>[];
  var okm = <int>[];
  int i = 1;
  while (okm.length < length) {
    t = hmac.convert([...t, ...info, i]).bytes;
    okm.addAll(t);
    i++;
  }
  return Uint8List.fromList(okm.sublist(0, length));
}

(Uint8List, Uint8List) _kdfRk(Uint8List rk, Uint8List dhOut) {
  final prk = _hkdfExtract(rk, dhOut);
  final okm = _hkdfExpand(prk, utf8.encode('DoubleRatchet'), 64);
  return (
    Uint8List.fromList(okm.sublist(0, 32)),
    Uint8List.fromList(okm.sublist(32, 64)),
  );
}

(Uint8List, Uint8List) _kdfCk(Uint8List ck) {
  final hmacMk = Hmac(sha256, ck);
  final mk = Uint8List.fromList(hmacMk.convert([0x01]).bytes);
  final hmacCk = Hmac(sha256, ck);
  final nextCk = Uint8List.fromList(hmacCk.convert([0x02]).bytes);
  return (nextCk, mk);
}

Uint8List _padTo4KB(Uint8List payload) {
  const blockSize = 4096;
  final minCapacity = 4 + payload.length;
  final targetSize = ((minCapacity + blockSize - 1) ~/ blockSize) * blockSize;
  final padLen = targetSize - minCapacity;

  final random = Random.secure();
  final result = Uint8List(targetSize);
  ByteData.view(result.buffer).setUint32(0, payload.length, Endian.big);
  result.setRange(4, 4 + payload.length, payload);

  for (int i = 0; i < padLen; i++) {
    result[4 + payload.length + i] = random.nextInt(256);
  }
  return result;
}

Uint8List _toBytes(dynamic input) {
  if (input is Uint8List) return input;
  if (input is List<int>) return Uint8List.fromList(input);
  if (input is String) {
    if (RegExp(r'^[0-9a-fA-F]{64}$').hasMatch(input)) {
      final list = <int>[];
      for (int i = 0; i < input.length; i += 2) {
        list.add(int.parse(input.substring(i, i + 2), radix: 16));
      }
      return Uint8List.fromList(list);
    }
    try {
      return base64.decode(input);
    } catch (_) {
      return Uint8List.fromList(utf8.encode(input));
    }
  }
  try {
    final dynamic b = input.extractBytes();
    if (b is List<int>) return Uint8List.fromList(b);
  } catch (_) {}
  try {
    final dynamic b = input.bytes;
    if (b is List<int>) return Uint8List.fromList(b);
  } catch (_) {}
  throw ArgumentError('Cannot convert input to 32-byte key: $input');
}

bool _bytesEqual(List<int> a, List<int> b) {
  if (a.length != b.length) return false;
  for (int i = 0; i < a.length; i++) {
    if (a[i] != b[i]) return false;
  }
  return true;
}
