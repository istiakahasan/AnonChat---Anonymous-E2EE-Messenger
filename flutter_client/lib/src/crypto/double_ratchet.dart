import 'dart:convert';
import 'dart:math';
import 'dart:typed_data';
import 'package:crypto/crypto.dart';

/// Representation of an X25519 KeyPair for Double Ratchet sessions.
class RatchetKeyPair {
  final Uint8List secretKey;
  final Uint8List publicKey;

  RatchetKeyPair({required this.secretKey, required this.publicKey});

  Uint8List get privateKey => secretKey;

  factory RatchetKeyPair.fromSecret(dynamic secret) {
    final priv = _toBytes(secret);
    final pub = x25519Base(priv);
    return RatchetKeyPair(secretKey: priv, publicKey: pub);
  }

  factory RatchetKeyPair.fromPair(dynamic priv, dynamic pub) {
    final privBytes = _toBytes(priv);
    final pubBytes = pub != null ? _toBytes(pub) : x25519Base(privBytes);
    return RatchetKeyPair(secretKey: privBytes, publicKey: pubBytes);
  }

  factory RatchetKeyPair.generate([dynamic sodium]) {
    if (sodium != null) {
      try {
        final dynamic pair = sodium.crypto.box.keyPair();
        return RatchetKeyPair(
          secretKey: _toBytes(pair.secretKey),
          publicKey: _toBytes(pair.publicKey),
        );
      } catch (_) {}
    }
    final random = Random.secure();
    final priv = Uint8List(32);
    for (int i = 0; i < 32; i++) {
      priv[i] = random.nextInt(256);
    }
    final pub = x25519Base(priv);
    return RatchetKeyPair(secretKey: priv, publicKey: pub);
  }
}

/// Double Ratchet Engine for Flutter / Dart.
///
/// Usage:
/// ```dart
/// final ratchet = DoubleRatchet(sodium);
/// // Alice:
/// final aliceSession = ratchet.initSenderSession(sharedSecret, bobPublicKey);
/// // Bob:
/// final bobSession = ratchet.initReceiverSession(sharedSecret, bobRatchetKeyPair);
/// ```
class DoubleRatchet {
  final dynamic sodium;

  DoubleRatchet([this.sodium]);

  /// Alice: initializes Double Ratchet sender session from X3DH shared secret.
  ///
  /// Inputs:
  /// - `sharedSecret`: 32-byte output from X3DH
  /// - `bobPublicKey`: Bob's signed prekey public key (DH ratchet key published by Bob)
  ///
  /// Initialize:
  /// - `DHs` = a NEW X25519 keypair generated by Alice for this session
  /// - `DHr` = `bobPublicKey`
  /// - `RK` = HKDF(shared_secret, DH(DHs_private, DHr), info="root")
  /// - `CKs` = HKDF(RK, info="chain-send")
  /// - `CKr` = null
  /// - `Ns` = 0 (messages sent in current chain)
  /// - `Nr` = 0 (messages received in current chain)
  /// - `PNs` = 0 (previous chain length)
  /// - `MKSKIPPED` = empty map
  /// - `BOB_FIRST_MESSAGE` = false
  DoubleRatchetSession initSenderSession(
    dynamic sharedSecret,
    dynamic bobPublicKey,
  ) {
    final sharedSecretBytes = _toBytes(sharedSecret);
    final bobPubBytes = _toBytes(bobPublicKey);

    // 1. Generate a NEW X25519 keypair for Alice
    final dhs = RatchetKeyPair.generate(sodium);

    // 2. DH(DHs_private, DHr)
    final dhOut = _computeDh(dhs.secretKey, bobPubBytes);

    // 3. RK, CKs = KDF_RK(shared_secret, DH)
    final (newRk, cks) = _kdfRk(sharedSecretBytes, dhOut);

    return DoubleRatchetSession(
      dhs: dhs,
      dhr: bobPubBytes,
      rootKey: newRk,
      sendingChainKey: cks,
      receivingChainKey: null,
      ns: 0,
      nr: 0,
      pns: 0,
      mkSkipped: {},
      bobFirstMessage: false,
      sodium: sodium,
    );
  }

  /// Bob: initializes Double Ratchet receiver session from X3DH shared secret.
  ///
  /// Inputs:
  /// - `sharedSecret`: same 32 bytes from X3DH
  /// - `bobRatchetKeyPair`: Bob's signed prekey keypair (private + public)
  ///
  /// Initialize:
  /// - `DHs` = `bobRatchetKeyPair`
  /// - `DHr` = null (Bob has not yet received Alice's ratchet key)
  /// - `RK` = `sharedSecret` (before the first DH ratchet step)
  /// - `CKs` = null
  /// - `CKr` = null
  /// - `Ns` = 0, `Nr` = 0, `PNs` = 0
  /// - `MKSKIPPED` = empty map
  /// - `BOB_FIRST_MESSAGE` = true (flag to handle the initial state specially)
  DoubleRatchetSession initReceiverSession(
    dynamic sharedSecret,
    dynamic bobRatchetKeyPair,
  ) {
    final sharedSecretBytes = _toBytes(sharedSecret);
    final keypair = _normalizeKeyPair(bobRatchetKeyPair);

    return DoubleRatchetSession(
      dhs: keypair,
      dhr: null,
      rootKey: Uint8List.fromList(sharedSecretBytes),
      sendingChainKey: null,
      receivingChainKey: null,
      ns: 0,
      nr: 0,
      pns: 0,
      mkSkipped: {},
      bobFirstMessage: true,
      sodium: sodium,
    );
  }

  // Static convenience wrappers matching earlier functional signatures
  static DoubleRatchetSession initSenderState({
    required List<int> sharedSecret,
    required List<int> bobRatchetPublic,
    dynamic sodium,
  }) {
    return DoubleRatchet(sodium).initSenderSession(sharedSecret, bobRatchetPublic);
  }

  static DoubleRatchetSession initReceiverState({
    required List<int> sharedSecret,
    required dynamic bobRatchetKeypair,
    dynamic sodium,
  }) {
    return DoubleRatchet(sodium).initReceiverSession(sharedSecret, bobRatchetKeypair);
  }

  Uint8List _computeDh(Uint8List priv, Uint8List pub) {
    if (sodium != null) {
      try {
        final dynamic crypto = sodium.crypto;
        if (crypto != null && crypto.scalarmult != null) {
          return _toBytes(crypto.scalarmult(priv, pub));
        }
      } catch (_) {}
      try {
        if (sodium.cryptoScalarmult != null) {
          return _toBytes(sodium.cryptoScalarmult(priv, pub));
        }
      } catch (_) {}
    }
    return x25519(priv, pub);
  }

  RatchetKeyPair _normalizeKeyPair(dynamic kp) {
    if (kp is RatchetKeyPair) return kp;
    if (kp is Map) {
      final priv = _toBytes(kp['secretKey'] ?? kp['privateKey'] ?? kp['private'] ?? kp['priv']);
      final pub = kp['publicKey'] ?? kp['public'] ?? kp['pub'];
      final pubBytes = pub != null ? _toBytes(pub) : x25519Base(priv);
      return RatchetKeyPair(secretKey: priv, publicKey: pubBytes);
    }
    if (kp is List<int>) {
      final priv = Uint8List.fromList(kp);
      return RatchetKeyPair(secretKey: priv, publicKey: x25519Base(priv));
    }
    try {
      final dynamic privObj = kp.secretKey ?? kp.privateKey;
      final dynamic pubObj = kp.publicKey;
      final priv = _toBytes(privObj);
      final pub = pubObj != null ? _toBytes(pubObj) : x25519Base(priv);
      return RatchetKeyPair(secretKey: priv, publicKey: pub);
    } catch (_) {}
    throw ArgumentError('Unsupported keypair format for bobRatchetKeyPair: $kp');
  }
}

/// Double Ratchet Session state and transition machine.
class DoubleRatchetSession {
  RatchetKeyPair dhs;
  Uint8List? dhr;
  Uint8List rootKey;
  Uint8List? sendingChainKey;
  Uint8List? receivingChainKey;
  int ns;
  int nr;
  int pns;
  Map<String, Uint8List> mkSkipped;
  bool bobFirstMessage;
  dynamic sodium;

  DoubleRatchetSession({
    required this.dhs,
    this.dhr,
    required this.rootKey,
    this.sendingChainKey,
    this.receivingChainKey,
    this.ns = 0,
    this.nr = 0,
    this.pns = 0,
    Map<String, Uint8List>? mkSkipped,
    this.bobFirstMessage = false,
    this.sodium,
  }) : mkSkipped = mkSkipped ?? {};

  /// Encrypts an outbound plaintext message.
  ///
  /// 1. Advances sending chain: (next_cks, mk) = KDF_CK(cks)
  /// 2. Increments Ns
  /// 3. Creates header { dh_pub, pn, n }
  Map<String, dynamic> ratchetEncrypt(dynamic plaintext) {
    if (sendingChainKey == null) {
      throw StateError('Missing sending chain key');
    }
    final (nextCks, mk) = _kdfCk(sendingChainKey!);
    sendingChainKey = nextCks;

    final header = {
      'dh_pub': base64.encode(dhs.publicKey),
      'pn': pns,
      'n': ns,
    };
    ns += 1;

    final plainBytes = _toBytes(plaintext);
    final padded = _padTo4KB(plainBytes);

    final nonce = Uint8List(12);
    ByteData.view(nonce.buffer).setUint32(8, header['n'] as int, Endian.big);

    return {
      'header': header,
      'ciphertext': base64.encode(padded),
      'nonce': base64.encode(nonce),
      'mk': base64.encode(mk),
    };
  }

  /// Processes received envelope and advances receiving / DH ratchet.
  void onMessageReceived(Map<String, dynamic> header) {
    final peerDhBytes = base64.decode(header['dh_pub'] as String);
    if (dhr == null || !_bytesEqual(dhr!, peerDhBytes)) {
      pns = ns;
      ns = 0;
      nr = 0;
      dhr = Uint8List.fromList(peerDhBytes);

      // DH Ratchet step 1: Derives receiving chain key
      final dhOutRx = x25519(dhs.secretKey, dhr!);
      final (newRkRx, ckr) = _kdfRk(rootKey, dhOutRx);
      rootKey = newRkRx;
      receivingChainKey = ckr;

      // DH Ratchet step 2: Generate fresh DHs and derive sending chain key
      dhs = RatchetKeyPair.generate(sodium);
      final dhOutTx = x25519(dhs.secretKey, dhr!);
      final (newRkTx, cks) = _kdfRk(rootKey, dhOutTx);
      rootKey = newRkTx;
      sendingChainKey = cks;

      bobFirstMessage = false;
    }

    if (receivingChainKey != null) {
      final (nextCkr, _) = _kdfCk(receivingChainKey!);
      receivingChainKey = nextCkr;
      nr += 1;
      bobFirstMessage = false;
    }
  }
}

// ---------------------------------------------------------------------------
// Pure Dart RFC 7748 Curve25519 Scalar Multiplication (X25519)
// ---------------------------------------------------------------------------
final BigInt _p = (BigInt.one << 255) - BigInt.from(19);
final BigInt _a24 = BigInt.from(121665);
final Uint8List _baseU = Uint8List(32)..[0] = 9;

BigInt _decodeLittleEndian(Uint8List bytes) {
  var result = BigInt.zero;
  for (var i = bytes.length - 1; i >= 0; i--) {
    result = (result << 8) | BigInt.from(bytes[i]);
  }
  return result;
}

Uint8List _encodeLittleEndian(BigInt value, int length) {
  final bytes = Uint8List(length);
  var v = value;
  for (var i = 0; i < length; i++) {
    bytes[i] = (v & BigInt.from(0xff)).toInt();
    v >>= 8;
  }
  return bytes;
}

Uint8List x25519(Uint8List scalar, Uint8List uBytes) {
  final clamped = Uint8List.fromList(scalar);
  clamped[0] &= 248;
  clamped[31] &= 127;
  clamped[31] |= 64;

  final BigInt u = _decodeLittleEndian(uBytes) & ((BigInt.one << 255) - BigInt.one);

  BigInt x1 = u;
  BigInt x2 = BigInt.one;
  BigInt z2 = BigInt.zero;
  BigInt x3 = u;
  BigInt z3 = BigInt.one;
  int swap = 0;

  for (int t = 254; t >= 0; t--) {
    final byteIndex = t ~/ 8;
    final bitIndex = t % 8;
    final kt = (clamped[byteIndex] >> bitIndex) & 1;
    swap ^= kt;
    if (swap == 1) {
      final t1 = x2; x2 = x3; x3 = t1;
      final t2 = z2; z2 = z3; z3 = t2;
    }
    swap = kt;

    final A = (x2 + z2) % _p;
    final AA = (A * A) % _p;
    final B = (x2 - z2) % _p;
    final BB = (B * B) % _p;
    final E = (AA - BB) % _p;
    final C = (x3 + z3) % _p;
    final D = (x3 - z3) % _p;
    final DA = (D * A) % _p;
    final CB = (C * B) % _p;
    x3 = ((DA + CB) * (DA + CB)) % _p;
    z3 = (x1 * ((DA - CB) * (DA - CB))) % _p;
    x2 = (AA * BB) % _p;
    z2 = (E * (AA + _a24 * E)) % _p;
  }

  if (swap == 1) {
    final t1 = x2; x2 = x3; x3 = t1;
    final t2 = z2; z2 = z3; z3 = t2;
  }

  final res = (x2 * z2.modPow(_p - BigInt.from(2), _p)) % _p;
  return _encodeLittleEndian(res, 32);
}

Uint8List x25519Base(Uint8List scalar) => x25519(scalar, _baseU);

// ---------------------------------------------------------------------------
// HKDF & KDF Chains
// ---------------------------------------------------------------------------
Uint8List _hkdfExtract(List<int> salt, List<int> ikm) {
  final hmac = Hmac(sha256, salt.isEmpty ? Uint8List(32) : salt);
  return Uint8List.fromList(hmac.convert(ikm).bytes);
}

Uint8List _hkdfExpand(List<int> prk, List<int> info, int length) {
  final hmac = Hmac(sha256, prk);
  var t = <int>[];
  var okm = <int>[];
  int i = 1;
  while (okm.length < length) {
    t = hmac.convert([...t, ...info, i]).bytes;
    okm.addAll(t);
    i++;
  }
  return Uint8List.fromList(okm.sublist(0, length));
}

(Uint8List, Uint8List) _kdfRk(Uint8List rk, Uint8List dhOut) {
  final prk = _hkdfExtract(rk, dhOut);
  final okm = _hkdfExpand(prk, utf8.encode('AnonChat_DoubleRatchet_RootKDF'), 64);
  return (
    Uint8List.fromList(okm.sublist(0, 32)),
    Uint8List.fromList(okm.sublist(32, 64)),
  );
}

(Uint8List, Uint8List) _kdfCk(Uint8List ck) {
  final hmacMk = Hmac(sha256, ck);
  final mk = Uint8List.fromList(hmacMk.convert([0x01]).bytes);
  final hmacCk = Hmac(sha256, ck);
  final nextCk = Uint8List.fromList(hmacCk.convert([0x02]).bytes);
  return (nextCk, mk);
}

Uint8List _padTo4KB(Uint8List payload) {
  const blockSize = 4096;
  final minCapacity = 4 + payload.length;
  final targetSize = ((minCapacity + blockSize - 1) ~/ blockSize) * blockSize;
  final padLen = targetSize - minCapacity;

  final random = Random.secure();
  final result = Uint8List(targetSize);
  ByteData.view(result.buffer).setUint32(0, payload.length, Endian.big);
  result.setRange(4, 4 + payload.length, payload);

  for (int i = 0; i < padLen; i++) {
    result[4 + payload.length + i] = random.nextInt(256);
  }
  return result;
}

Uint8List _toBytes(dynamic input) {
  if (input is Uint8List) return input;
  if (input is List<int>) return Uint8List.fromList(input);
  if (input is String) {
    if (RegExp(r'^[0-9a-fA-F]{64}$').hasMatch(input)) {
      final list = <int>[];
      for (int i = 0; i < input.length; i += 2) {
        list.add(int.parse(input.substring(i, i + 2), radix: 16));
      }
      return Uint8List.fromList(list);
    }
    try {
      return base64.decode(input);
    } catch (_) {
      return Uint8List.fromList(utf8.encode(input));
    }
  }
  try {
    final dynamic b = input.extractBytes();
    if (b is List<int>) return Uint8List.fromList(b);
  } catch (_) {}
  try {
    final dynamic b = input.bytes;
    if (b is List<int>) return Uint8List.fromList(b);
  } catch (_) {}
  throw ArgumentError('Cannot convert input to 32-byte key: $input');
}

bool _bytesEqual(List<int> a, List<int> b) {
  if (a.length != b.length) return false;
  for (int i = 0; i < a.length; i++) {
    if (a[i] != b[i]) return false;
  }
  return true;
}
